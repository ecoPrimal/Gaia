async function postJson(url, body) {
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), 4000);
  try {
    const r = await fetch(url, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(body),
      signal: ctrl.signal
    });
    clearTimeout(timer);
    return { ok: r.ok, status: r.status };
  } catch (e) {
    clearTimeout(timer);
    return { ok: false, error: e.message };
  }
}

async function inject(source) {
  const content = taoText(source);
  const results = [];
  for (const node of FAMILY) {
    let r;
    if (node.kind === 'emit') {
      r = await postJson(node.url, { channel: 'thoughts', content, meta: { source: 'AUTO-TAO', system: 'CIVILIZATIONAL' } });
    } else if (node.kind === 'shout') {
      r = await postJson(node.url, { channel: 'thoughts', content, meta: { source: 'AUTO-TAO' } });
    } else if (node.kind === 'eat') {
      r = await postJson(node.url, { food: content });
    } else {
      try {
        const ctrl = new AbortController();
        const timer = setTimeout(() => ctrl.abort(), 3000);
        const resp = await fetch(node.url, { signal: ctrl.signal });
        clearTimeout(timer);
        r = { ok: resp.ok, status: resp.status };
      } catch (e) {
        r = { ok: false, error: e.message };
      }
    }
    results.push({ name: node.name, ...r });
    console.log('AUTO TAO → ' + node.name + ': ' + (r.ok ? 'INJECTED' : (r.error || r.status)));
  }
  return { tao: TAO, content, results };
}

